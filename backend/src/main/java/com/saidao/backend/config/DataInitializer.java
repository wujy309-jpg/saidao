    /**
     * 迁移:notifications.type 需要能容纳实体里新增的团队事件枚举值。
     *
     * <p>背景:旧实现不区分数据库方言，一律 {@code DROP TABLE notifications} 再用 H2 语法
     * （{@code GENERATED BY DEFAULT AS IDENTITY}）重建。在 MySQL 上重建必然失败，异常又被
     * 当成「可忽略」吞掉，且迁移标记写不进去，于是<b>每次启动都会把通知表删掉一次</b>
     * （2026-10-08 线上事故:通知表连同历史数据被删）。现改为纯非破坏性迁移:
     *
     * <ul>
     *   <li>表不存在 → 交给 Hibernate 的 ddl-auto 建表，不插手；</li>
     *   <li>非 MySQL 方言 → 列定义由 Hibernate 维护，不执行任何 DDL；</li>
     *   <li>MySQL 且 ENUM 取值已覆盖实体全部枚举 → 什么都不做（幂等）；</li>
     *   <li>MySQL 且缺枚举值 → 只做 {@code ALTER TABLE ... MODIFY COLUMN} 扩容取值。</li>
     * </ul>
     *
     * <p>全流程不删表、不删数据、不依赖迁移标记（每次启动按实体定义自检，可自我修复）；
     * 任何失败只记日志并继续启动，绝不阻断应用。
     */
    void migrateNotificationSchema() {
        try {
            if (!tableExists("notifications")) {
                log.info("notifications 表尚不存在，交由 Hibernate 建表，跳过枚举迁移");
                return;
            }
            String product = databaseProductName();
            if (!product.contains("mysql") && !product.contains("mariadb")) {
                log.info("当前数据库方言为 {}，notifications.type 由 Hibernate 按实体维护，跳过枚举迁移", product);
                return;
            }
            String columnType = notificationTypeColumnType();
            if (columnType == null) {
                log.warn("未查询到 notifications.type 列定义，跳过枚举迁移");
                return;
            }
            Set<String> required = Arrays.stream(Notification.NotificationType.values())
                    .map(Enum::name)
                    .collect(Collectors.toCollection(LinkedHashSet::new));
            if (columnType.toLowerCase(Locale.ROOT).startsWith("enum(")) {
                Set<String> missing = new LinkedHashSet<>(required);
                missing.removeAll(parseEnumValues(columnType));
                if (missing.isEmpty()) {
                    return;
                }
                log.warn("notifications.type 缺少枚举值 {}，执行非破坏性扩容(不删表、不删数据)", missing);
                jdbcTemplate.execute("ALTER TABLE notifications MODIFY COLUMN type ENUM("
                        + required.stream().map(v -> "'" + v + "'").collect(Collectors.joining(","))
                        + ") NOT NULL");
                log.info("notifications.type 枚举已扩容至 {} 个取值", required.size());
                return;
            }
            Integer length = parseCharLength(columnType);
            int needed = required.stream().mapToInt(String::length).max().orElse(0);
            if (length != null && length >= needed) {
                return;
            }
            log.warn("notifications.type 当前定义为 {}，可能容纳不下最长枚举值({} 字符)，跳过自动改写，请人工确认",
                    columnType, needed);
        } catch (Exception e) {
            log.error("通知表枚举迁移失败(未删除任何数据，应用继续启动): {}", e.getMessage(), e);
        }
    }

    /** 表是否存在；兼容 H2(大写) 与 MySQL(小写) 的元数据大小写差异 */
    private boolean tableExists(String table) {
        Boolean exists = jdbcTemplate.execute((ConnectionCallback<Boolean>) connection -> {
            DatabaseMetaData meta = connection.getMetaData();
            for (String candidate : new String[]{table, table.toUpperCase(Locale.ROOT)}) {
                try (ResultSet rs = meta.getTables(connection.getCatalog(), null, candidate, new String[]{"TABLE"})) {
                    if (rs.next()) {
                        return true;
                    }
                }
            }
            return false;
        });
        return Boolean.TRUE.equals(exists);
    }

    private String databaseProductName() {
        String name = jdbcTemplate.execute(
                (ConnectionCallback<String>) connection -> connection.getMetaData().getDatabaseProductName());
        return name == null ? "" : name.toLowerCase(Locale.ROOT);
    }

    /** MySQL:读取列的完整定义，例如 {@code enum('REPLY','LIKE_POST')} */
    private String notificationTypeColumnType() {
        List<String> types = jdbcTemplate.queryForList(
                "SELECT COLUMN_TYPE FROM INFORMATION_SCHEMA.COLUMNS "
                        + "WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'notifications' AND COLUMN_NAME = 'type'",
                String.class);
        return types.isEmpty() ? null : types.get(0);
    }

    /** 从 {@code enum('A','B')} 解析出取值集合 */
    static Set<String> parseEnumValues(String columnType) {
        Set<String> values = new LinkedHashSet<>();
        Matcher matcher = Pattern.compile("'([^']*)'").matcher(columnType);
        while (matcher.find()) {
            values.add(matcher.group(1));
        }
        return values;
    }

    /** 从 {@code varchar(40)} 解析长度，非字符类型返回 null */
    static Integer parseCharLength(String columnType) {
        Matcher matcher = Pattern.compile("(?:var)?char\\((\\d+)\\)").matcher(columnType.toLowerCase(Locale.ROOT));
        return matcher.find() ? Integer.valueOf(matcher.group(1)) : null;
    }
    
    /**
     * 已有数据时：按名称同步 competitions.json —— 更新官方链接/富标签等字段，并插入 JSON 中新增的竞赛（upsert）
     */
    private void syncCompetitionData() {
        try {
            ClassPathResource resource = new ClassPathResource("competitions.json");
            if (!resource.exists()) return;
            try (InputStream in = resource.getInputStream()) {
                Map<String, List<Competition>> data = objectMapper.readValue(in, new TypeReference<>() {});
                List<Competition> seed = data.get("competitions");
                if (seed == null) return;
                int updated = 0;
                int inserted = 0;
                for (Competition sc : seed) {
                    var existingOpt = competitionRepository.findByNameContainingIgnoreCase(sc.getName()).stream()
                            .findFirst();
                    if (existingOpt.isPresent()) {
                        Competition existing = existingOpt.get();
                        boolean changed = false;
                        if (sc.getOfficialUrl() != null && !sc.getOfficialUrl().isBlank()
                                && !sc.getOfficialUrl().equals(existing.getOfficialUrl())) {
                            existing.setOfficialUrl(sc.getOfficialUrl());
                            changed = true;
                        }
                        if (sc.getCatalogList() != null && !Objects.equals(sc.getCatalogList(), existing.getCatalogList())) {
                            existing.setCatalogList(sc.getCatalogList());
                            changed = true;
                        }
                        if (sc.getBaoyanBonus() != null && !Objects.equals(sc.getBaoyanBonus(), existing.getBaoyanBonus())) {
                            existing.setBaoyanBonus(sc.getBaoyanBonus());
                            changed = true;
                        }
                        if (sc.getEntryFee() != null && !Objects.equals(sc.getEntryFee(), existing.getEntryFee())) {
                            existing.setEntryFee(sc.getEntryFee());
                            changed = true;
                        }
                        if (sc.getRules() != null && !Objects.equals(sc.getRules(), existing.getRules())) {
                            existing.setRules(sc.getRules());
                            changed = true;
                        }
                        if (changed) {
                            competitionRepository.save(existing);
                            updated++;
                        }
                    } else {
                        competitionRepository.save(sc);
                        inserted++;
                    }
                }
                log.info("竞赛数据同步完成：{} 条种子数据（更新 {}，新增 {}）", seed.size(), updated, inserted);
            }
        } catch (Exception e) {
            log.error("竞赛数据同步失败", e);
        }
    }
    
